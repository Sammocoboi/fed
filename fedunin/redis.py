print(r.hgetall("user:1"))


# команды
# r.set(k,v) сохраняет значения 
# r.get() получает значение 
# r.incr(k) увелечение на 1
# r.decr(k) уменьшение на 1
# r.set(k,v,ex=60) - сохраняем на 60 сек дальше детарминируем
# r.ttl(k) - оставшаеся время от ex
#r.hset(k,mapping=dict) - записываем поля
#r.hget(k,field) - читаем одно поле hash 
#r.hgetall(k) - читаем все поля
#r.hincrby(k,field,n) - увелечивает 
#r.delete(k) - удаляем ключ
#r.exist(k) - проверяет существование ключа 
#r.type(k) - узнает тип значения 

# самое главное что нужно знать про Redis
# python и redis - независимые процессу друг от друга 
# python не хранит значения Redis внутри переменной r
# это переменная которая представает клиент который отправляет
# команды отдельному серверу
# когда мы пишем r.get(...) происхсодит запись на сервере 
# когда вызываем r.get(...) python запрашивает актуальные значения оттуда

